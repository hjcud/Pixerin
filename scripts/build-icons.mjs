import fs from "node:fs/promises";
import path from "node:path";
import { PNG } from "pngjs";

const root = path.resolve(import.meta.dirname, ".."),
  folder = path.join(root, "src", "icons");
const files = (await fs.readdir(folder))
  .filter((name) => /^[a-z][a-z0-9-]*\.png$/.test(name))
  .sort();
if (!files.length) throw new Error("No source icons found in src/icons");
const pixels = {};
for (const file of files) {
  const png = PNG.sync.read(await fs.readFile(path.join(folder, file)));
  if (png.width !== 16 || png.height !== 16)
    throw new Error(`${file}: keep the native 16x16 canvas`);
  const rows = Array.from({ length: 16 }, () => "");
  for (let i = 0; i < 256; i++) {
    const alpha = png.data[i * 4 + 3];
    if (alpha !== 0 && alpha !== 255)
      throw new Error(
        `${file}: use fully opaque pixels or full transparency; no antialiasing`,
      );
    rows[Math.floor(i / 16)] += alpha === 255 ? "#" : ".";
  }
  pixels[file.slice(0, -4)] = rows;
}
const svg = (name, color) => {
  if (!pixels[name]) throw new Error(`Missing required icon: ${name}`);
  const runs = [];
  pixels[name].forEach((row, y) => {
    for (let x = 0; x < 16; x++) {
      if (row[x] !== "#") continue;
      const start = x;
      while (x + 1 < 16 && row[x + 1] === "#") x++;
      runs.push(`M${start} ${y}h${x - start + 1}v1H${start}z`);
    }
  });
  const cells = runs.join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16" fill="${color}" shape-rendering="crispEdges"><path d="${cells}"/></svg>`;
};
const data = `// Generated by scripts/build-icons.mjs. Edit the neighboring PNG files instead.\nexport const ICON_PIXELS = Object.freeze(Object.fromEntries(Object.entries(${JSON.stringify(pixels, null, 2)}).map(([name, rows]) => [name, Object.freeze(rows)])));\n`;
const masks = `/* Generated from src/icons/*.png. Do not edit. */
summary::before { mask: url("data:image/svg+xml,${encodeURIComponent(svg("chevron-right", "#000"))}") center / 16px 16px no-repeat; }
.request-progress.in-progress .request-progress-heading strong::before { mask: url("data:image/svg+xml,${encodeURIComponent(svg("circle", "#000"))}") center / 16px 16px no-repeat; }
select { background-image: url("data:image/svg+xml,${encodeURIComponent(svg("chevron-down", "#83908e"))}") !important; }
`;
const gallery = `<!doctype html><html lang="en"><meta charset="utf-8"><title>Pixel Mat icon catalog</title><style>body{font:14px system-ui;background:#eee;color:#222;margin:32px}main{display:grid;grid-template-columns:repeat(auto-fill,minmax(150px,1fr));gap:16px}figure{margin:0;padding:16px;background:white;border:1px solid #ccc;text-align:center}img{width:64px;height:64px;image-rendering:pixelated;background:repeating-conic-gradient(#ddd 0 25%,#fff 0 50%) 0 / 16px 16px}figcaption{margin-top:12px}</style><h1>Pixel Mat icons — 16 × 16</h1><p>Edit the PNG files in this folder, then run <code>pnpm icons:build</code> from the project root. Opaque pixels become the UI color; transparent pixels are empty.</p><main>${files.map((file) => `<figure><a href="${file}"><img src="${file}" alt="${file}"></a><figcaption>${file}</figcaption></figure>`).join("\n")}</main></html>\n`;
// Validate every source before replacing any generated output.
for (const [file, content] of [
  ["data.mjs", data],
  ["masks.css", masks],
  ["catalog.html", gallery],
]) {
  const destination = path.join(folder, file);
  if (process.argv.includes("--check")) {
    if ((await fs.readFile(destination, "utf8").catch(() => null)) !== content)
      throw new Error(`${file} is stale. Run pnpm icons:build.`);
  } else await fs.writeFile(destination, content);
}
console.log(
  `${files.length} editable icons ${process.argv.includes("--check") ? "verified" : "built"}`,
);
