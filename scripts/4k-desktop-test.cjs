if (require("./test-runner.cjs").bootstrap(__filename)) return;
const {_electron}=require("./test-electron.cjs"), fs=require("node:fs/promises"),path=require("node:path"),assert=require("node:assert/strict"),{PNG}=require("pngjs");
(async()=>{
  const root=path.resolve(__dirname,".."), profile=await require("./test-runner.cjs").createProfile("4k-document-");
  const {createDocument,ensureLayers,validateDocument}=await import("../src/core.mjs");
  let doc=ensureLayers(validateDocument({...createDocument(1,1,"4K fixture"),width:4096,height:4096,pixels:Array(4096*4096).fill(0)}));
  doc.pixels[4096*4096-1]=7;
  await fs.writeFile(path.join(profile,"draft.json"),JSON.stringify(doc)); doc=null;
  const env={...process.env,PIXELTOOL_USER_DATA:profile}; delete env.ELECTRON_RUN_AS_NODE;
  let app=await _electron.launch({executablePath:require("electron"),args:[root],env});
  try {
    let page=await require("./first-editor.cjs")(app); page.setDefaultTimeout(60000);
    await require("./editor-ready.cjs")(page);
    const errors=[];page.on("pageerror",e=>errors.push(e.message));
    assert.equal(await page.locator("#pixel-canvas").getAttribute("width"),"4096");
    const last=()=>page.locator("#pixel-canvas").evaluate(c=>Array.from(c.getContext("2d").getImageData(4095,4095,1,1).data));
    assert.deepEqual(await last(),[80,168,137,255]);
    await page.locator("#new-btn").click();await page.locator("#new-4k").click();
    assert.equal(await page.locator("#new-width").inputValue(),"3840");
    assert.equal(await page.locator("#new-height").inputValue(),"2160");
    assert.equal(await page.locator("#new-width").getAttribute("max"),"3840");
    await page.locator("#new-height").fill("2161");await page.locator('#new-form button[type="submit"]').click();
    await page.waitForFunction(()=>document.getElementById("toast").textContent.includes("8,294,400"));
    assert.ok(await page.locator("#new-dialog").isVisible());await page.keyboard.press("Escape");
    await page.locator("#fit-btn").click();
    assert.ok(parseFloat(await page.locator("#zoom-label").innerText())<100);
    await page.locator("#zoom-menu > summary").click();await page.locator("#zoom-value").fill("6400");await page.locator("#zoom-apply").click();
    assert.ok(await page.locator("#overlay-canvas").evaluate(c=>c.width<=4096&&c.height<=4096));
    await page.locator("#fit-btn").click();
    await page.locator("#palette button").nth(7).click(); await page.locator('[data-tool="pencil"]').click();
    const rect=await page.locator("#overlay-canvas").boundingBox();
    const x=Math.floor(4096/2),y=Math.floor(4096/2);
    await page.mouse.click(rect.x+(x+.5)*rect.width/4096,rect.y+(y+.5)*rect.height/4096);
    const middle=()=>page.locator("#pixel-canvas").evaluate(c=>Array.from(c.getContext("2d").getImageData(2048,2048,1,1).data));
    assert.deepEqual(await middle(),[80,168,137,255]);
    await page.keyboard.press("Control+z");assert.equal((await middle())[3],0);
    await page.keyboard.press("Control+Shift+z");assert.deepEqual(await middle(),[80,168,137,255]);
    const saved=path.join(profile,"4k.pixeltool"),png=path.join(profile,"4k.png");
    await app.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},saved);
    await page.keyboard.press("Control+Shift+s");await page.waitForFunction(()=>document.getElementById("toast").textContent.includes("4k.pixeltool"));
    const data=JSON.parse(await fs.readFile(saved,"utf8"));assert.equal(data.layers[0].pixels[2048*4096+2048],7);assert.equal(data.layers[0].pixels.at(-1),7);
    await app.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},png);
    await page.locator("#export-btn").click();await page.waitForFunction(()=>document.getElementById("toast").textContent.includes("4k.png"));
    const image=PNG.sync.read(await fs.readFile(png));assert.equal(image.width,4096);assert.equal(image.height,4096);assert.equal(image.data.at(-1),255);
    await fs.mkdir(path.join(root,"artifacts"),{recursive:true});await page.screenshot({path:path.join(root,"artifacts","4k-editor.png")});
    assert.deepEqual(errors,[]);
    await app.close();app=await _electron.launch({executablePath:require("electron"),args:[root],env});
    page=await require("./first-editor.cjs")(app);page.setDefaultTimeout(60000);await require("./editor-ready.cjs")(page);
    assert.deepEqual(await last(),[80,168,137,255]);assert.deepEqual(await middle(),[80,168,137,255]);
    console.log("PASS: 4096-square drawing, bounded 6400% overlay, fit, undo/redo, project/PNG save and restart; 4K UHD preset.");
  }finally{await app.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
